"""Markdown API documentation rendered deterministically from a generated OpenAPI document.

Rendering from the OpenAPI document (instead of from the raw suggestions) guarantees the
Markdown and the machine-readable spec never disagree.
"""

from __future__ import annotations

from typing import Any

_METHOD_ORDER = ["get", "post", "put", "patch", "delete"]


def _escape(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _schema_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return f"`{schema['$ref'].rsplit('/', 1)[-1]}`"
    kind = schema.get("type", "object")
    if isinstance(kind, list):
        kind = " \\| ".join(kind)
    if schema.get("format"):
        kind = f"{kind} ({schema['format']})"
    if schema.get("enum"):
        kind = f"{kind}: {', '.join(map(str, schema['enum']))}"
    return kind


def render_markdown(document: dict[str, Any]) -> str:
    info = document.get("info", {})
    paths: dict[str, dict[str, Any]] = document.get("paths", {})
    schemas: dict[str, Any] = document.get("components", {}).get("schemas", {})
    lines: list[str] = [
        f"# {info.get('title', 'API')}",
        "",
        f"Version `{info.get('version', '0.1.0')}` - OpenAPI `{document.get('openapi')}`",
        "",
        info.get("description", ""),
        "",
        "> Generated by ai-requirements-agent. Every operation lists the evidence chunk ids it",
        "> was derived from and a confidence score; review before implementation.",
        "",
        "## Authentication",
        "",
        "All operations require `Authorization: Bearer <JWT>`.",
        "",
        "## Endpoints",
        "",
        "| Method | Path | Summary | Confidence |",
        "| --- | --- | --- | --- |",
    ]
    operations: list[tuple[str, str, dict[str, Any]]] = []
    for path in sorted(paths):
        for method in sorted(paths[path], key=_METHOD_ORDER.index):
            operation = paths[path][method]
            operations.append((path, method, operation))
            lines.append(
                f"| {method.upper()} | `{path}` | {_escape(operation.get('summary', ''))} | "
                f"{operation.get('x-confidence', '-')} |"
            )
    if not operations:
        lines.append("| - | - | No endpoints were generated | - |")

    by_tag: dict[str, list[tuple[str, str, dict[str, Any]]]] = {}
    for path, method, operation in operations:
        by_tag.setdefault(operation.get("tags", ["default"])[0], []).append(
            (path, method, operation)
        )

    for tag in sorted(by_tag):
        lines += ["", f"## {tag}", ""]
        for path, method, operation in by_tag[tag]:
            lines += [f"### `{method.upper()} {path}`", "", operation.get("summary", ""), ""]
            lines.append(f"- Operation id: `{operation.get('operationId')}`")
            if operation.get("x-related-stories"):
                lines.append(f"- User stories: {', '.join(operation['x-related-stories'])}")
            evidence = operation.get("x-evidence") or []
            lines.append(
                f"- Evidence: {', '.join(f'`{e}`' for e in evidence) if evidence else 'none'}"
            )
            params = operation.get("parameters") or []
            if params:
                lines += ["", "| Parameter | In | Type | Required |", "| --- | --- | --- | --- |"]
                for param in params:
                    lines.append(
                        f"| `{param['name']}` | {param['in']} | "
                        f"{_schema_type(param.get('schema', {}))} | "
                        f"{'yes' if param.get('required') else 'no'} |"
                    )
            body = operation.get("requestBody")
            if body:
                schema = body["content"]["application/json"]["schema"]
                lines += ["", f"Request body: {_schema_type(schema)}"]
            lines += ["", "| Status | Description | Body |", "| --- | --- | --- |"]
            for status, response in operation.get("responses", {}).items():
                if "$ref" in response:
                    name = response["$ref"].rsplit("/", 1)[-1]
                    lines.append(f"| {status} | {name} | `Error` |")
                    continue
                content = response.get("content", {}).get("application/json", {})
                body_type = _schema_type(content["schema"]) if content else "-"
                lines.append(
                    f"| {status} | {_escape(response.get('description', ''))} | {body_type} |"
                )
            lines.append("")

    model_names = [n for n in sorted(schemas) if not n.endswith(("Create", "Update", "Page"))]
    lines += ["## Models", ""]
    for name in model_names:
        schema = schemas[name]
        lines += [f"### `{name}`", ""]
        if schema.get("description"):
            lines += [_escape(schema["description"]), ""]
        required = set(schema.get("required", []))
        lines += ["| Field | Type | Required | Description |", "| --- | --- | --- | --- |"]
        for field_name, field_schema in schema.get("properties", {}).items():
            lines.append(
                f"| `{field_name}` | {_schema_type(field_schema)} | "
                f"{'yes' if field_name in required else 'no'} | "
                f"{_escape(field_schema.get('description', ''))} |"
            )
        for rel in schema.get("x-relationships", []):
            lines.append(f"| _relationship_ | {rel['kind']} -> `{rel['target']}` | - | |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"
